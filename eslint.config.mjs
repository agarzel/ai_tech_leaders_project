import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

// Dependency direction: app → core → db; ui is importable by app only.
// Only @devmentor/db may import @mikro-orm/*; core never imports next/react.
const mikroOrm = { group: ["@mikro-orm/*"], message: "Only @devmentor/db may import @mikro-orm/*." };
const pkg = (name, reason) => ({ name, message: reason });
const pkgGroup = (group, reason) => ({ group, message: reason });

const uiPaths = [
  pkg("@devmentor/core", "ui is standalone – pass data in via props."),
  pkg("@devmentor/db", "ui is standalone – pass data in via props."),
  pkg("@devmentor/app", "ui must not depend on the app."),
];

// Mock Service Worker simulates the API only in Storybook (.storybook/, stories/); package code never
// depends on it, so unit coverage and the app bundle stay free of it (POSTEP.md C16).
const msw = pkgGroup(["msw", "msw/*", "msw-storybook-addon", "msw-storybook-addon/*"], "MSW belongs to Storybook only (.storybook/, stories/).");

const restrict = (files, { paths = [], patterns = [] }) => ({
  files,
  rules: { "no-restricted-imports": ["error", { paths, patterns }] },
});

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  {
    settings: { next: { rootDir: "packages/app/" } },
  },
  restrict(["packages/db/**"], {
    paths: [
      pkg("@devmentor/core", "db is the bottom layer: app → core → db."),
      pkg("@devmentor/ui", "db must not depend on UI."),
      pkg("@devmentor/app", "db must not depend on the app."),
      pkg("react", "db must not depend on React."),
    ],
    patterns: [pkgGroup(["next", "next/*"], "db must not depend on Next.js.")],
  }),
  restrict(["packages/core/**"], {
    paths: [
      pkg("@devmentor/ui", "core must not depend on UI."),
      pkg("@devmentor/app", "core must not depend on the app."),
      pkg("react", "core must not import React."),
    ],
    patterns: [pkgGroup(["next", "next/*"], "core must not import Next.js."), mikroOrm],
  }),
  restrict(["packages/ui/**"], { paths: uiPaths, patterns: [mikroOrm] }),
  restrict(["packages/ui/src/**"], { paths: uiPaths, patterns: [mikroOrm, msw] }),
  // The shadcn CLI generates `import { cn } from "cn"`; primitives must use the configured cn that
  // knows the design-system utilities (h-control, type-label …) – POSTEP.md F5/B25.
  restrict(["packages/ui/src/components/**"], {
    paths: [...uiPaths, pkg("cn", 'Import cn from "@devmentor/ui/lib/utils" (configured for design-system classes).')],
    patterns: [mikroOrm, msw],
  }),
  // A <form> without method="post" is submitted as GET before hydration (or with JS off), putting its named fields –
  // CrudForm's email and password – into the URL, browser history and server logs. Found by ZAP in lesson 16
  // (threat model T-13) after every review had passed it; this rule keeps it from coming back. Forms with an `action`
  // (React server or function actions) are exempt: React posts them itself and rejects an explicit method.
  // Keep it the only `no-restricted-syntax` block for these files – a later one would replace it, not extend it.
  // Regression test: scripts/form-method-rule.test.mjs.
  {
    files: ["packages/app/src/**/*.{tsx,jsx}", "packages/ui/src/**/*.{tsx,jsx}"],
    rules: {
      "no-restricted-syntax": [
        "error",
        {
          selector:
            "JSXOpeningElement[name.name='form']:not(:has(JSXAttribute[name.name='action'])):not(:has(JSXAttribute[name.name='method'][value.value=/^post$/i]))",
          message: 'Give every <form> method="post" – without it a submit before hydration sends the fields in the URL (threat model T-13).',
        },
      ],
    },
  },
  restrict(["packages/app/**"], {
    paths: [pkg("@devmentor/db", "app talks to the database through @devmentor/core services.")],
    patterns: [mikroOrm],
  }),
  globalIgnores([
    "**/.next/**",
    "**/.next-test/**",
    // Build dir of the dev server started by .ai/scripts/test-env-up.sh.
    "**/.next-test-env/**",
    // Cezar task worktrees: full copies of the repo, linted in their own checkout, not as part of this one.
    ".ai/cezar/**",
    // Installed third-party skills (npx skills add): vendored, never edited here, and their asset scripts are not
    // product code. #130 brought in JS assets that failed to parse and turned main's lint red.
    ".agents/skills/**",
    "**/out/**",
    "**/build/**",
    "**/next-env.d.ts",
    "packages/db/src/migrations/**",
    "coverage/**",
    ".vitest/**",
    "**/storybook-static/**",
    // Generated by `npx msw init` – regenerate it, never edit by hand.
    "packages/ui/.storybook/public/mockServiceWorker.js",
    // Build output of the clickable prototypes, course material, and the vendored review engine (G08): not product code.
    "packages/ui/.storybook/public/prototypes/**",
    "lekcja-07/**",
    ".ai/prototypes/epik-01/engine/**",
  ]),
]);

export default eslintConfig;
