#!/usr/bin/env node
// Keeps the component tables of `.ai/docs/design-system.md` in step with the single source of truth,
// `packages/ui/.storybook/blocks/components-data.ts` (lesson 6, D-S4). Node built-ins only.
// Usage: node scripts/design-system-doc.mjs          rewrite the generated section
//        node scripts/design-system-doc.mjs --check  fail (exit 1) when the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const DATA_FILE = "packages/ui/.storybook/blocks/components-data.ts";
export const DOC_FILE = ".ai/docs/design-system.md";
export const BEGIN_MARKER = "<!-- BEGIN:components-table (generated by `npm run docs:design-system`, do not edit by hand) -->";
export const END_MARKER = "<!-- END:components-table -->";

export class DocError extends Error {}

/** Evaluates the TypeScript data file (types stripped) and returns `{ GROUPS, COMPONENTS }`. */
export async function loadData(source) {
  const js = stripTypeScriptTypes(source);
  return import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
}

/** The path a developer imports from, without the package prefix; the one non-import row shows its class. */
export function importPath(importLine) {
  const fromImport = /from "@devmentor\/ui\/([^"]+)"/.exec(importLine);
  if (fromImport) return fromImport[1];
  const fromClass = /className="([^"]+)"/.exec(importLine);
  if (fromClass) return `class="${fromClass[1]}"`;
  throw new DocError(`Cannot derive an import path from: ${importLine}`);
}

const cell = (text) => text.replace(/\|/g, "\\|");

/** Markdown for every group: a heading and a table of its components, in data order. */
export function renderTables({ GROUPS, COMPONENTS }) {
  return GROUPS.map((group) => {
    const rows = COMPONENTS.filter((entry) => entry.group === group.name).map(
      (entry) => `| ${cell(entry.name)} | \`${importPath(entry.importLine)}\` | ${cell(entry.when)} | ${cell(entry.whenNot)} |`,
    );
    return [`### ${group.name}`, "", "| Component | Import path | Use when | Not when |", "|---|---|---|---|", ...rows].join("\n");
  }).join("\n\n");
}

/** The document with the text between the markers replaced by `generated`. */
export function replaceGenerated(markdown, generated) {
  const begin = markdown.indexOf(BEGIN_MARKER);
  const end = markdown.indexOf(END_MARKER);
  if (begin === -1 || end === -1 || end < begin) {
    throw new DocError(`${DOC_FILE} must contain ${BEGIN_MARKER} followed by ${END_MARKER}.`);
  }
  return `${markdown.slice(0, begin + BEGIN_MARKER.length)}\n\n${generated}\n\n${markdown.slice(end)}`;
}

/** Writes the document, or with `--check` only compares. Returns the exit code. */
export async function run(
  argv = [],
  {
    root = ROOT,
    readFile = (f) => readFileSync(f, "utf8"),
    writeFile = (f, text) => writeFileSync(f, text),
    log = console.log,
  } = {},
) {
  const check = argv.includes("--check");
  const docPath = path.join(root, DOC_FILE);
  try {
    const data = await loadData(readFile(path.join(root, DATA_FILE)));
    const current = readFile(docPath);
    const next = replaceGenerated(current, renderTables(data));
    if (next === current) {
      log(`✓ ${DOC_FILE} is up to date with ${DATA_FILE}.`);
      return 0;
    }
    if (check) {
      log(`✗ ${DOC_FILE} is out of date with ${DATA_FILE}. Run: npm run docs:design-system`);
      return 1;
    }
    writeFile(docPath, next);
    log(`✓ ${DOC_FILE} updated from ${DATA_FILE}.`);
    return 0;
  } catch (error) {
    if (!(error instanceof DocError)) throw error;
    log(`✗ ${error.message}`);
    return 1;
  }
}

export function isEntryPoint(argv1, moduleUrl = import.meta.url) {
  return argv1 !== undefined && pathToFileURL(argv1).href === moduleUrl;
}

if (isEntryPoint(process.argv[1])) {
  process.exitCode = await run(process.argv.slice(2));
}
